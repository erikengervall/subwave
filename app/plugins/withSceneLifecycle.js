// Expo config plugin: adopt the UIScene life cycle on iOS.
//
// An app built with the iOS 27 SDK that has no scene manifest is killed at
// launch on iOS 27 (`_UIApplicationEvaluateRuntimeIssueForNoSceneLifecycleAdoption`).
// The SDK 57 template still starts React Native from the app delegate, so this
// does what the SDK 58 template does: a scene manifest, a SceneDelegate built
// on Expo's own ExpoAppSceneDelegate (it creates the window, starts React
// Native into it and forwards URL, activity and lifecycle events), and an app
// delegate that only creates the factory.
//
// App Intents (src/intents) still reach JS on a launch straight into the
// background: iOS connects a scene for an intent launch even though the app
// is never shown, and React Native starts there.
//
// Drop this plugin when the app moves to Expo SDK 58, whose template does the
// same.
//
// Usage in app.json plugins: "./plugins/withSceneLifecycle"

const fs = require('fs');
const path = require('path');
const {
  IOSConfig,
  withAppDelegate,
  withDangerousMod,
  withInfoPlist,
  withXcodeProject,
} = require('@expo/config-plugins');

const SCENE_DELEGATE = `internal import Expo

// Generated by plugins/withSceneLifecycle.js. ExpoAppSceneDelegate creates the
// window, starts React Native into it, and forwards scene events to the app
// delegate.
@objc(SceneDelegate)
class SceneDelegate: ExpoAppSceneDelegate {}
`;

// The SDK 57 template's window + startReactNative block in didFinishLaunching.
const START_BLOCK =
  /#if os\(iOS\) \|\| os\(tvOS\)\s*window = UIWindow\(frame: UIScreen\.main\.bounds\)\s*factory\.startReactNative\(\s*withModuleName: "main",\s*in: window,\s*launchOptions: launchOptions\)\s*#endif\n?/;

function withSceneManifest(config) {
  return withInfoPlist(config, (cfg) => {
    cfg.modResults.UIApplicationSceneManifest = {
      UIApplicationSupportsMultipleScenes: false,
      UISceneConfigurations: {
        UIWindowSceneSessionRoleApplication: [
          {
            UISceneConfigurationName: 'Default Configuration',
            UISceneDelegateClassName: '$(PRODUCT_MODULE_NAME).SceneDelegate',
          },
        ],
      },
    };
    return cfg;
  });
}

function withSceneAppDelegate(config) {
  return withAppDelegate(config, (cfg) => {
    if (cfg.modResults.language !== 'swift') {
      throw new Error('withSceneLifecycle: expected a Swift AppDelegate');
    }
    let src = cfg.modResults.contents;
    if (src.includes('ExpoReactNativeFactoryProvider')) return cfg;

    // Fail the prebuild rather than ship an app that starts React Native
    // twice, or never: a template change has to be looked at by hand.
    if (!START_BLOCK.test(src) || !src.includes('class AppDelegate: ExpoAppDelegate {')) {
      throw new Error(
        'withSceneLifecycle: AppDelegate.swift no longer matches the SDK 57 template; update the plugin.',
      );
    }
    src = src.replace(
      'class AppDelegate: ExpoAppDelegate {',
      'class AppDelegate: ExpoAppDelegate, ExpoReactNativeFactoryProvider {',
    );
    src = src.replace(
      START_BLOCK,
      '    // SceneDelegate creates the window and starts React Native (plugins/withSceneLifecycle.js).\n',
    );
    cfg.modResults.contents = src;
    return cfg;
  });
}

function withSceneDelegateFile(config) {
  config = withDangerousMod(config, [
    'ios',
    (cfg) => {
      const projectName = IOSConfig.XcodeUtils.getProjectName(cfg.modRequest.projectRoot);
      const file = path.join(cfg.modRequest.platformProjectRoot, projectName, 'SceneDelegate.swift');
      fs.writeFileSync(file, SCENE_DELEGATE);
      return cfg;
    },
  ]);
  return withXcodeProject(config, (cfg) => {
    const projectName = IOSConfig.XcodeUtils.getProjectName(cfg.modRequest.projectRoot);
    const filepath = `${projectName}/SceneDelegate.swift`;
    if (!cfg.modResults.hasFile(filepath)) {
      IOSConfig.XcodeUtils.addBuildSourceFileToGroup({
        filepath,
        groupName: projectName,
        project: cfg.modResults,
      });
    }
    return cfg;
  });
}

module.exports = function withSceneLifecycle(config) {
  config = withSceneManifest(config);
  config = withSceneAppDelegate(config);
  return withSceneDelegateFile(config);
};
